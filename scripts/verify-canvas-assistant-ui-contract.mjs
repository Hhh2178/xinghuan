import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const read = (path) => readFileSync(join(process.cwd(), path), 'utf8');
const canvas = read('apps/web/src/components/Canvas.tsx');
const entry = read('apps/web/src/components/CanvasAssistant.tsx');
const shell = read('apps/web/src/components/canvas-assistant/CanvasAssistantShell.tsx');
const composer = read('apps/web/src/components/canvas-assistant/AssistantComposer.tsx');
const session = read('apps/web/src/components/canvas-assistant/useAssistantSession.ts');
const supervisor = read('apps/web/src/components/canvas-agent/CanvasRunSupervisor.tsx');
const runApi = read('apps/web/src/components/canvas-agent/canvas-run-api.ts');
const styles = read('apps/web/src/styles/index.css');

assert.match(canvas, /<CanvasAssistant nodes=\{nodes\} edges=\{edges\} activeCanvasId=\{activeId\} \/>/);
assert.match(canvas, /penguin:append-assistant-context/);
assert.match(entry, /CanvasAssistantShell/);
assert.ok(entry.split('\n').length < 30, 'CanvasAssistant entry must remain thin');
assert.match(shell, /agent-assistant-workbench/);
assert.match(shell, /CanvasRunSupervisor/);
assert.match(shell, /penguin:open-run-supervisor/);
assert.match(composer, /onPaste=\{pasteImage\}/);
assert.match(composer, /accept="image\/png,image\/jpeg,image\/webp"/);
assert.match(session, /penguin:append-assistant-context/);
assert.match(session, /idempotencyKey: crypto\.randomUUID\(\)/);
assert.match(session, /conversationId: sessionId/);
assert.match(session, /getMediaItemsFromData/);
assert.doesNotMatch(session, /localStorage/);
assert.match(supervisor, /只读权威投影/);
assert.match(supervisor, /projection\.command\('pause'\)/);
assert.match(supervisor, /projection\.command\('cancel'\)/);
assert.match(runApi, /new EventSource/);
assert.match(runApi, /events\/stream/);
assert.match(styles, /\.agent-assistant-workbench \{/);
assert.match(styles, /\.canvas-agent-node \{/);
assert.match(styles, /@media \(max-width: 720px\)/);
assert.match(styles, /@media \(prefers-reduced-motion: reduce\)/);
assert.doesNotMatch(shell, /canvas-assistant-panel|canvas-assistant-fab|linear-gradient|backdrop-filter/);

console.log('canvas assistant and supervision UI contract: ok');
